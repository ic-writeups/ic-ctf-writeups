# Lo que hace el programa por cada byte i (0..47):
#
#   lut = tabla_lookup[i % 32]
#   X   = (lut XOR input[i] + ecx) & 0xFF   # índice en tabla_cmp
#   resultado = tabla_cmp[X]
#   ¿resultado == tabla_ref[i]?  →  sigue / falla
#
# Para invertir, despejamos input[i]:
#   1. X = tabla_cmp_inversa[tabla_ref[i]]     # encontramos el índice que da ese valor
#   2. input[i] = ((X - ecx) & 0xFF) XOR lut   # despejamos input
#
# ecx empieza en 0x1F y suma 0x11 cada iteración (mod 256)
# =============================================================================

# Paso 1: construir tabla_cmp inversa
inv_cmp = {}
for idx, val in enumerate(tabla_cmp):
    inv_cmp[val] = idx

# Paso 2: recuperar cada byte del token
token_bytes = []
ecx = 0x1F

print(f"{'i':>3}  {'ecx':>5}  {'ref':>5}  {'X':>5}  {'lut':>5}  {'input':>7}  char")
print("-" * 55)

for i in range(48):
    ref_val = tabla_ref[i]
    X       = inv_cmp[ref_val]           # índice inverso en tabla_cmp
    lut     = tabla_lookup[i % 32]
    inp     = ((X - ecx) & 0xFF) ^ lut  # byte del token

    char = chr(inp) if 0x20 <= inp < 0x7F else f"\\x{inp:02x}"
    print(f"{i:>3}  {ecx:#06x}  {ref_val:#04x}  {X:#04x}  {lut:#04x}  {inp:#06x}   {char}")

    token_bytes.append(inp)
    ecx = (ecx + 0x11) & 0xFF

print()
print("*" * 55)
print("TOKEN:", bytes(token_bytes).decode('utf-8'))
print("*" * 55)